import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge' });
const errors = [];
await mkdir('test-results', { recursive: true });
try {
  for (const mobile of [false, true]) {
    const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 }, acceptDownloads: true });
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.goto(process.env.SOL_URL || 'http://127.0.0.1:5173/');
    await page.waitForFunction(() => !!window.sol);
    await page.evaluate(() => window.sol.debugFocus('saturn'));
    await page.waitForTimeout(1200);
    await page.screenshot({ path: `test-results/${mobile ? 'mobile' : 'desktop'}-saturn.png` });
    const physics = await page.evaluate(async () => {
      const s = window.sol.system;
      const { positionFromElements, elementsAt } = await import('/src/core/kepler.ts');
      const { centuriesSinceJ2000 } = await import('/src/core/time.ts');
      const earth = s.nodes.get('earth');
      const expected = positionFromElements(elementsAt(earth.body.elements, earth.body.rates, centuriesSinceJ2000(window.sol.currentTime)));
      return Math.hypot(earth.ecliptic.x - expected.x * 100, earth.ecliptic.y - expected.y * 100, earth.ecliptic.z - expected.z * 100);
    });
    assert.ok(physics < 1e-6, 'scene uses mean anomaly, not mean longitude');
    await page.click('#toggle-trails');
    assert.equal(await page.evaluate(() => window.sol.system.trails.get('earth').line.visible), false);
    await page.click('#toggle-trails');
    assert.equal(await page.evaluate(() => window.sol.system.trails.get('earth').line.visible), true);
    await page.click('#open-explorer');
    await page.fill('#body-search', 'Europa');
    await page.click('[data-body="europa"]');
    await page.waitForTimeout(2800);
    assert.equal(await page.textContent('#p-title'), '木卫二');
    await page.click('[data-view="system"]');
    await page.evaluate(() => { const e = document.getElementById('size'); e.value = '0'; e.dispatchEvent(new Event('input')); });
    await page.waitForTimeout(100);
    const ratio = await page.evaluate(() => window.sol.system.bodyRadiusWorld('sun') / window.sol.system.bodyRadiusWorld('earth'));
    assert.ok(Math.abs(ratio - 696000 / 6371) < 1e-8);
    await page.evaluate(() => { const e = document.getElementById('size'); e.value = '100'; e.dispatchEvent(new Event('input')); });
    await page.click('#open-explorer');
    await page.fill('#travel-date', '2000-01-01');
    await page.click('#travel');
    assert.ok(Math.abs(await page.evaluate(() => window.sol.currentTime) - 2451545) < 2);
    await page.click('#reverse');
    const before = await page.evaluate(() => window.sol.currentTime);
    await page.waitForTimeout(300);
    assert.ok(await page.evaluate(() => window.sol.currentTime) < before);
    await page.click('[data-close="explorer"]');
    await page.click('#start-tour');
    await page.waitForTimeout(3000);
    assert.equal(await page.getAttribute('#tour-caption', 'hidden'), null);
    await page.click('#tour-next');
    assert.match(await page.textContent('#chapter-title'), /地月/);
    await page.screenshot({ path: `test-results/${mobile ? 'mobile' : 'desktop'}-tour.png` });
    await page.click('#tour-stop');
    await page.click('#open-letter');
    await page.fill('#dedication', '在这个宇宙里，很高兴遇见你。<不是 HTML>');
    await page.click('#show-letter');
    assert.match(await page.getAttribute('#app', 'class'), /cinema/);
    assert.match(await page.textContent('#dedication-display'), /<不是 HTML>/);
    await page.screenshot({ path: `test-results/${mobile ? 'mobile' : 'desktop'}-letter.png` });
    await page.click('#exit-cinema');
    const downloadWait = page.waitForEvent('download');
    await page.click('#capture');
    const download = await downloadWait;
    await download.saveAs(`test-results/${mobile ? 'mobile' : 'desktop'}-postcard.png`);
    assert.equal(await download.failure(), null);
    await page.click('#open-explorer');
    await page.uncheck('#bloom-effect');
    await page.uncheck('#comet-effect');
    await page.click('[data-overview="all"]');
    await page.waitForTimeout(3200);
    assert.equal(await page.evaluate(() => window.sol.system.comet.group.visible), false);
    await page.screenshot({ path: `test-results/${mobile ? 'mobile' : 'desktop'}-overview.png` });
    await page.click('#open-explorer');
    await page.click('#visit-comet');
    await page.waitForTimeout(1200);
    assert.equal(await page.evaluate(() => window.sol.system.comet.group.visible), true);
    await page.screenshot({ path: `test-results/${mobile ? 'mobile' : 'desktop'}-comet.png` });
    await page.close();
  }
  assert.deepEqual(errors, []);
  console.log('PASS desktop + mobile: search, moon selection, true scale, date, reverse, tour, safe dedication, PNG download; no browser errors.');
} finally { await browser.close(); }
